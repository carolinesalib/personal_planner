module SystemAuthHelper
  def sign_in_via_browser(user)
    OmniAuth.config.mock_auth[:google_oauth2] = OmniAuth::AuthHash.new(
      provider: user.provider,
      uid: user.uid,
      info: {
        email: user.email,
        name: user.name,
        image: user.avatar_url
      }
    )

    visit login_path
    click_on "Continue with Google"
  end
end
